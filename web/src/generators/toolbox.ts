import { stringify } from "yaml";
import { TOOLBOX_INSTALLER, toolboxPin } from "../catalog/releases";
import { testlabRoles, type Config } from "../model/dataspace";
import type { Bundle } from "./types";

const STARTER_KIT = "https://github.com/eclipse-tractusx/tractusx-starter-kit";
const INSTALLER = TOOLBOX_INSTALLER;
const ACTION = "eclipse-tractusx/tractusx-starter-kit/developer-toolbox@main";

/** developer-toolbox/toolbox.yaml as the toolbox reads it: the keys it would otherwise default. */
export function toolboxYaml(config: Config): string {
  const document: Record<string, unknown> = {
    participants: config.participants.map((participant) => ({
      name: participant.name,
      bpn: participant.bpn,
      connector: participant.connector,
      dtr: participant.connector && participant.dtr,
    })),
    "stand-ins": {
      echo: config.standIns.echo,
      "stub-caller": config.standIns.stubCaller,
      "submodel-server": config.standIns.submodelServer,
    },
  };
  if (config.testlab.version) {
    const roles = testlabRoles(config);
    document.testlab = { version: config.testlab.version, sut: roles.sut, engine: roles.engine };
  } else {
    document.testlab = { version: "" };
  }
  return `# Generated by the Eclipse Tractus-X Starter Kit configurator.
# SPDX-License-Identifier: Apache-2.0
#
# A developer toolbox configuration. Keys left out take the toolbox defaults
# (Umbrella ${toolboxPin.umbrellaChart}, IdentityHub ${toolboxPin.identityhubChart}):
# ${STARTER_KIT}/blob/main/developer-toolbox/toolbox.yaml

${stringify(document)}`;
}

export function toolboxBundle(config: Config): Bundle {
  const roles = testlabRoles(config);
  const withTestlab = Boolean(config.testlab.version);
  const workflow = `# Generated by the Eclipse Tractus-X Starter Kit configurator.
# SPDX-License-Identifier: Apache-2.0
#
# Copy to .github/workflows/ and toolbox.yaml to ci/toolbox.yaml.
name: E2E on an Eclipse Tractus-X dataspace

on:
  pull_request:
  workflow_dispatch:

permissions:
  contents: read

jobs:
  e2e:
    runs-on: ubuntu-latest
    timeout-minutes: 45
    steps:
      - uses: actions/checkout@v4
      - uses: ${ACTION}
        id: toolbox
        with:
          config: ci/toolbox.yaml
${
  withTestlab
    ? `      - name: Run a TCK against ${roles.sut}
        run: testlab run my.tck --config "\${{ steps.toolbox.outputs.variables-file }}"
`
    : `      - name: Your tests
        run: cat "\${{ steps.toolbox.outputs.participants-file }}"
`
}      - if: failure()
        uses: eclipse-tractusx/tractusx-starter-kit/developer-toolbox/diagnostics@main
`;

  const up = `#!/usr/bin/env bash
# Generated by the Eclipse Tractus-X Starter Kit configurator.
# SPDX-License-Identifier: Apache-2.0
#
# Starts this dataspace in a kind cluster on your Docker, with the tx-toolbox
# command of the Eclipse Tractus-X Developer Toolbox (installed on the first run).
set -euo pipefail
cd "$(dirname "$0")"

toolbox="$(command -v tx-toolbox || true)"
if [ -z "$toolbox" ]; then
  curl -fsSL ${INSTALLER} | bash
  toolbox="\${TX_TOOLBOX_BIN:-$HOME/.local/bin}/tx-toolbox"
fi
"$toolbox" up --config "$PWD/toolbox.yaml" "$@"
`;

  const participants = config.participants
    .map((p) => `| \`${p.name}\` | \`${p.bpn}\` | ${p.connector ? "yes" : "no"} | ${p.connector && p.dtr ? "yes" : "no"} |`)
    .join("\n");
  const readme = `# Eclipse Tractus-X Developer Toolbox: ${config.participants.length} participants

A very small Eclipse Tractus-X dataspace for developing and testing on your machine or in
a GitHub runner: the decentralized-identity profile of Umbrella
${toolboxPin.umbrellaChart} in a kind cluster, deployed with Helm as in production.

| Participant | BPN | Connector | Digital Twin Registry |
| --- | --- | --- | --- |
${participants}

${withTestlab ? `TestLab ${config.testlab.version} tests \`${roles.sut}\` and drives \`${roles.engine}\`.\n` : ""}
## On your machine

You need Docker with about 6 GB of memory, Python 3.10 or later, and \`curl\`.

\`\`\`bash
./up.sh                    # installs tx-toolbox if needed, then: tx-toolbox up --config toolbox.yaml
\`\`\`

Or install the \`tx-toolbox\` command yourself, once, and use it from any folder:

\`\`\`bash
curl -fsSL ${INSTALLER} | bash
tx-toolbox up --config toolbox.yaml
\`\`\`

\`up.sh\` passes its arguments on: \`./up.sh --memory 6g --no-hosts\`. Then:

\`\`\`bash
tx-toolbox info     # URLs, DIDs, API keys
tx-toolbox down     # removes the cluster
\`\`\`

## In GitHub Actions

Copy \`toolbox.yaml\` to \`ci/toolbox.yaml\` and \`e2e.yaml\` to \`.github/workflows/\`.
The action's outputs are in the toolbox documentation:
${STARTER_KIT}/tree/main/developer-toolbox
`;

  return {
    name: "tractusx-developer-toolbox",
    run: ["./up.sh"],
    files: [
      { path: "README.md", content: readme, language: "markdown", summary: "The dataspace and how to start it." },
      { path: "toolbox.yaml", content: toolboxYaml(config), language: "yaml", summary: "The toolbox configuration: participants, stand-ins, TestLab." },
      { path: "up.sh", content: up, language: "shell", summary: "Starts the dataspace in kind on your Docker.", executable: true },
      { path: "e2e.yaml", content: workflow, language: "yaml", summary: "A GitHub Actions workflow that starts it in the runner." },
    ],
  };
}
