import { stringify } from "yaml";
import { releaseById, profileUrl, UMBRELLA_HELM_REPO, UMBRELLA_REPO, type Release } from "../catalog/releases";
import { profileById, umbrellaComponent, umbrellaComponents } from "../catalog/umbrella";
import { umbrellaSelection, type Config } from "../model/dataspace";
import type { Bundle, GeneratedFile } from "./types";

const HEADER = `# Generated by the Eclipse Tractus-X Starter Kit configurator.
# SPDX-License-Identifier: Apache-2.0
`;

/**
 * The Umbrella chart, started from one of its value profiles. values.yaml only
 * holds the difference to the profile: what to switch on and what to switch off.
 */
export function umbrellaBundle(config: Config): Bundle {
  const release = releaseById(config.releaseId);
  const profile = profileById(config.umbrella.profileId);
  const selected = umbrellaSelection(config);
  const inProfile = new Set(profile.enables);
  const namespace = config.umbrella.namespace;
  const basyx = config.umbrella.registry === "basyx" && selected.has("tx-data-provider");

  const values: Record<string, { enabled: boolean }> = {};
  for (const component of umbrellaComponents) {
    const on = selected.has(component.key);
    if (on !== inProfile.has(component.key)) values[component.key] = { enabled: on };
  }
  const added = [...selected].filter((key) => !inProfile.has(key));
  const removed = profile.enables.filter((key) => !selected.has(key));
  const valuesYaml =
    HEADER +
    `# Applied over the Umbrella profile ${profile.file} (Umbrella ${release.umbrellaChart}).\n` +
    (Object.keys(values).length
      ? `# It switches on: ${added.join(", ") || "nothing"}; and off: ${removed.join(", ") || "nothing"}.\n\n` +
        stringify(values)
      : "# The profile as it is: nothing to change.\n{}\n");

  const pull = `#!/usr/bin/env bash
${HEADER}
# Pulls the Umbrella chart, with every component chart inside it, and the value
# profile, so that install.sh needs no network for the charts.
set -euo pipefail
cd "$(dirname "$0")"

helm repo add tractusx-dev ${UMBRELLA_HELM_REPO} --force-update
helm pull tractusx-dev/umbrella --version ${release.umbrellaChart} --untar --untardir charts
curl -fsSL -o profile.yaml \\
  ${profileUrl(release, profile.file)}
${basyx ? basyxPull(release) : ""}
echo "Pulled umbrella ${release.umbrellaChart} into charts/umbrella and the profile into profile.yaml."
`;

  const install = `#!/usr/bin/env bash
${HEADER}
# Installs the Umbrella release into the current kubectl context: a local
# cluster such as minikube or kind, with an ingress controller.
set -euo pipefail
cd "$(dirname "$0")"

[ -d charts/umbrella ] && [ -f profile.yaml ]${basyx ? " && [ -f basyx.yaml ]" : ""} || ./pull-charts.sh

${basyx ? BASYX_POST_RENDERER : ""}helm upgrade --install umbrella charts/umbrella \\
  --namespace ${namespace} --create-namespace \\
  -f profile.yaml \\
${basyx ? "  -f basyx.yaml \\\n" : ""}  -f values.yaml \\
${basyx ? '  ${post_renderer[@]+"${post_renderer[@]}"} \\\n' : ""}  --timeout 20m --wait

kubectl get pods --namespace ${namespace}
`;

  const uninstall = `#!/usr/bin/env bash
${HEADER}set -euo pipefail
helm uninstall umbrella --namespace ${namespace}
`;

  const rows = [...selected]
    .map((key) => umbrellaComponent(key))
    .filter((component) => component !== undefined)
    .map((component) => `| \`${component.key}\` | ${component.name} | ${component.description} |`);
  const readme = `# Eclipse Tractus-X Umbrella: ${profile.name}

Umbrella chart **${release.umbrellaChart}** (${release.label}), started from the
\`${profile.file}\` profile, in the namespace \`${namespace}\`.

## Components

| Values key | Component | What it does |
| --- | --- | --- |
${rows.join("\n")}

## Run it

You need a Kubernetes cluster with an ingress controller (minikube with the
\`ingress\` addon, or kind), \`kubectl\`, \`helm\` and \`curl\`.

\`\`\`bash
./pull-charts.sh   # the Umbrella chart and its component charts, into charts/
./install.sh       # helm upgrade --install, then waits for the pods
\`\`\`

\`./uninstall.sh\` removes the release.
${basyx ? BASYX_README : ""}

The components answer on the hosts in the Umbrella's ingress values. Point them
at your cluster's IP in \`/etc/hosts\`, as the Umbrella documentation describes:
${UMBRELLA_REPO}/tree/${release.umbrellaRef}/docs/user

## Files

- \`values.yaml\`: your changes to the profile. Edit it to configure a component.
- \`pull-charts.sh\`: pulls the charts and the profile.
- \`install.sh\` and \`uninstall.sh\`: install and remove the release.
${
  basyx
    ? `- \`basyx.yaml\` (pulled): the Umbrella's overlay that swaps the data provider's registry.
- \`helm-plugins/basyx-post-render/\`: the Umbrella's post-renderer, for Helm 3 and Helm 4.
- \`check-registry.sh\`: checks the registry and prints its API base.
`
    : ""
}`;

  return {
    name: `tractusx-umbrella-${release.umbrellaChart}`,
    run: ["./pull-charts.sh", "./install.sh"],
    files: [
      { path: "README.md", content: readme, language: "markdown", summary: "What is in the release and how to start it." },
      { path: "values.yaml", content: valuesYaml, language: "yaml", summary: `Your changes to the ${profile.name} profile.` },
      { path: "pull-charts.sh", content: pull, language: "shell", summary: "Pulls the Umbrella chart and the profile.", executable: true },
      { path: "install.sh", content: install, language: "shell", summary: "Installs the release and waits for it.", executable: true },
      { path: "uninstall.sh", content: uninstall, language: "shell", summary: "Removes the release.", executable: true },
      ...(basyx ? basyxFiles(namespace) : []),
    ],
  };
}

// --- The Eclipse BaSyx Go registry: the Umbrella's digital-twin-basyx-bundle -----------

const BASYX_OVERLAY = "values-adopter-data-exchange-basyx.yaml";
const BASYX_POST_RENDER = "scripts/dtr-basyx-tests/post-render.py";

function basyxPull(release: Release): string {
  return `
# The Eclipse BaSyx Go registry: the Umbrella's overlay and its post-renderer, from
# the same tag as the profile.
curl -fsSL -o basyx.yaml \\
  ${profileUrl(release, BASYX_OVERLAY)}
curl -fsSL -o helm-plugins/basyx-post-render/post-render.py \\
  https://raw.githubusercontent.com/eclipse-tractusx/tractus-x-umbrella/${release.umbrellaRef}/${BASYX_POST_RENDER}
`;
}

/**
 * BaSyx chart 3.15.0 renders a cert-manager Issuer even with TLS off; the Umbrella's
 * post-renderer drops it. Helm 3 runs a post-renderer as an executable, Helm 4 only
 * as a plugin: this picks the form the installed Helm understands, and needs none
 * when cert-manager is in the cluster.
 */
const BASYX_POST_RENDERER = `# The Eclipse BaSyx Go registry's post-renderer, in the form this Helm understands.
post_renderer=()
if kubectl get crd issuers.cert-manager.io >/dev/null 2>&1; then
  echo "cert-manager is installed: no post-renderer needed."
else
  command -v python3 >/dev/null || { echo "python3 is needed for the BaSyx post-renderer." >&2; exit 1; }
  case "$(helm version --template '{{.Version}}')" in
    v3.*) post_renderer=(--post-renderer "$PWD/helm-plugins/basyx-post-render/post-render.sh") ;;
    *) export HELM_PLUGINS="$PWD/helm-plugins"; post_renderer=(--post-renderer basyx-post-render) ;;
  esac
fi

`;

const BASYX_README = `
## The Eclipse BaSyx Go registry

The data provider runs the Eclipse BaSyx Go Digital Twin Registry instead of the
Eclipse Tractus-X one: \`install.sh\` adds the Umbrella's
\`${BASYX_OVERLAY}\` after the profile. The EDCs, the test data
and the seeding stay as they are; only the registry and its database change.

| | Eclipse Tractus-X registry | Eclipse BaSyx Go registry |
| --- | --- | --- |
| In-cluster API base | \`http://umbrella-dataprovider-dtr:8080/api/v3\` | \`http://dataprovider-basyx-digital-twin-registry:8080/digital-twin-registry\` |
| Ingress | \`http://dataprovider-dtr.tx.test/semantics/registry/api/v3\` | \`http://dataprovider-basyx-dtr.tx.test/digital-twin-registry\` |
| Database | PostgreSQL 15 | PostgreSQL 16 or later, schema by a Job |

Add \`dataprovider-basyx-dtr.tx.test\` to your hosts like the other \`*.tx.test\`
hosts, then \`./check-registry.sh\` checks it and prints the API base to use.

Keep in mind:

- Until the schema Job has run, the registry pod restarts with
  \`relation "basyxsystem" does not exist\`. This is expected.
- It runs with ABAC off: every caller that reaches it sees all \`specificAssetIds\`,
  whatever its \`Edc-Bpn\`. Restrict access with the EDC access policy of the
  registry asset, not with \`externalSubjectId\`.
- \`helm uninstall\` keeps the database volume; delete the PVC to start over.

Details: ${UMBRELLA_REPO}/blob/main/docs/user/common/guides/basyx-dtr.md
`;

function basyxFiles(namespace: string): GeneratedFile[] {
  const plugin = `${HEADER}# A Helm 4 post-renderer plugin around the Umbrella's post-render.py. install.sh
# points HELM_PLUGINS here for its own run, so nothing is installed globally.
name: basyx-post-render
version: 0.1.0
type: postrenderer/v1
apiVersion: v1
runtime: subprocess
runtimeConfig:
  platformCommand:
    - command: "\${HELM_PLUGIN_DIR}/post-render.sh"
`;
  const wrapper = `#!/usr/bin/env sh
${HEADER}# Helm 3 runs this as --post-renderer; Helm 4 through plugin.yaml.
exec python3 "$(dirname "$0")/post-render.py"
`;
  const check = `#!/usr/bin/env bash
${HEADER}
# Checks the data provider's Eclipse BaSyx Go registry and prints its API base,
# in the cluster and through the ingress.
set -euo pipefail
host=dataprovider-basyx-dtr.tx.test
service=dataprovider-basyx-digital-twin-registry

kubectl get pods --namespace ${namespace} | grep -E 'basyx|NAME' || true
echo
echo "In the cluster:    http://$service:8080/digital-twin-registry"
echo "Through ingress:   http://$host/digital-twin-registry"
echo
if curl -fsS "http://$host/digital-twin-registry/health" >/dev/null 2>&1; then
  echo "Health: up"
  curl -fsS "http://$host/digital-twin-registry/shell-descriptors?limit=5" | python3 -m json.tool | head -40
else
  echo "Health: not reachable through $host. Is it in /etc/hosts and the pod ready?" >&2
  exit 1
fi
`;
  return [
    { path: "helm-plugins/basyx-post-render/plugin.yaml", content: plugin, language: "yaml", summary: "The post-renderer as a Helm 4 plugin." },
    { path: "helm-plugins/basyx-post-render/post-render.sh", content: wrapper, language: "shell", summary: "Runs the Umbrella's post-renderer (Helm 3 and 4).", executable: true },
    { path: "check-registry.sh", content: check, language: "shell", summary: "Checks the BaSyx registry and prints its API base.", executable: true },
  ];
}
